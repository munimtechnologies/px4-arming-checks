#!/usr/bin/env python3
"""pages.py: one static web page per PX4 health and arming check message, from an armcat.py build.

    python pages.py OUT_DIR --dest SITE_DIR [--base-url URL]

Reads summary.json and catalog-<tag>.json written by `armcat.py build` in OUT_DIR and writes to SITE_DIR:

  m/<slug>.html   one page per report (arming check, health failure, health warning), matched across releases
                  the same way as changes.py (by PX4 event ID, else by file name and message). Each page has the
                  message, the console text PX4 prints next to it, PX4's own description, the parameters, every
                  release with the message text and a link to its source line, and the source lines in the newest
                  release that has it;
  messages.html   every message, grouped by check file, each linking to its page;
  sitemap.xml     index.html, changes.html, messages.html and every message page under --base-url;
  pages.json      slug, key, event ID, check, kind, title and releases of every page.

If SITE_DIR already holds an index.html (armcat.py's catalogue page), one link to messages.html is added to it,
once. People search for the exact text QGroundControl shows ("Preflight Fail: ..."); a page per message lets
that search land on the check, its parameters and its source.

By MV2 of Munim, Inc.; made with AI agents. Apache-2.0.
PX4 source excerpts in the output are PX4-Autopilot code (BSD-3-Clause, Copyright (c) PX4 Development Team).
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import os
import re
import sys

import armcat
import changes

__version__ = "0.1.0"

BASE_URL = "https://munimv2.github.io/px4-arming-checks/"
SOURCE_MAX_LINES = 40
LINK_MARK = "<!-- pages.py: messages link -->"
RE_PLACEHOLDER = re.compile(r"\{\d+[^}]*\}")
STYLE = ("<style>body{font-family:system-ui,sans-serif;max-width:60rem;margin:auto;padding:1rem;line-height:1.45}"
         "code{background:#f4f4f4;padding:0 .2rem}pre{background:#f4f4f4;padding:.5rem;overflow-x:auto}"
         "table{border-collapse:collapse;margin:.4rem 0 1rem}td,th{border:1px solid #ddd;padding:.2rem .4rem;"
         "vertical-align:top;text-align:left}ul{margin:.2rem 0}</style>")
FOOT = ("PX4-Autopilot source excerpts: BSD-3-Clause, Copyright (c) PX4 Development Team. This page: CC BY 4.0, "
        "MV2, Munim, Inc. (mv2@munimtech.com). Made with AI agents working in MV2's name; generated by pages.py %s "
        "(Apache-2.0) from the output of armcat.py.")


def title_of(r):
    t = r.get("message") if r.get("message") is not None else (r.get("message_raw") or "(message not a literal)")
    return t.replace("\n", " ").strip()


def _slugify(s):
    return re.sub(r"[^a-z0-9_-]+", "-", s.lower()).strip("-")


def slug_for(k, rec, used):
    """A file-name-safe, unique slug: the event ID, or <check>-<hash of key> for reports without one."""
    eid = rec.get("event_id")
    if eid:
        base = _slugify(eid) or "report"
    else:
        base = "%s-%s" % (_slugify(armcat._check_name(rec["path"])) or "report",
                          hashlib.sha1(k.encode("utf-8")).hexdigest()[:8])
    s, n = base, 1
    while s in used:
        n += 1
        s = "%s-%d" % (base, n)
    used.add(s)
    return s


def collect(tags, by_tag):
    """One item per report key across releases, sorted by check file and message.

    Each item: key, slug, tags (releases that have it, in build order), latest_tag, rec (the record in latest_tag)
    and per_tag {tag: {"rec": first record by path and line, "calls": number of calls with this key}}.
    """
    tags = [t for t in tags if t in by_tag]
    items = {}
    for tag in tags:
        counts = {}
        for r in by_tag[tag]:
            if r.get("kind") in armcat.REPORT_KINDS:
                counts[armcat.key(r)] = counts.get(armcat.key(r), 0) + 1
        for k, r in changes.first_by_key(by_tag[tag]).items():
            items.setdefault(k, {"key": k, "per_tag": {}})["per_tag"][tag] = {"rec": r, "calls": counts[k]}
    out = []
    for it in items.values():
        it["tags"] = [t for t in tags if t in it["per_tag"]]
        it["latest_tag"] = it["tags"][-1]
        it["rec"] = it["per_tag"][it["latest_tag"]]["rec"]
        it["check"] = armcat._check_name(it["rec"]["path"])
        it["title"] = title_of(it["rec"])
        out.append(it)
    used = set()
    for it in sorted(out, key=lambda x: x["key"]):
        it["slug"] = slug_for(it["key"], it["rec"], used)
    out.sort(key=lambda x: (x["check"].lower(), x["title"].lower(), x["key"]))
    return out


def _params(r):
    doc = list(r.get("params_doc") or [])
    near = [p for p in (r.get("params_near") or []) if p not in doc and not p.startswith("_")]
    return doc, near


def _kind_bits(r):
    bits = []
    if r.get("log") or r.get("log_raw"):
        bits.append("log level %s" % (r.get("log") or r.get("log_raw")))
    if r.get("component"):
        bits.append("health component %s" % r["component"])
    if r.get("modes"):
        bits.append("flight modes %s" % "|".join(r["modes"]))
    elif r.get("modes_raw"):
        bits.append("flight modes %s" % r["modes_raw"])
    return bits


def _meta_description(it, all_tags):
    r = it["rec"]
    doc, near = _params(r)
    ps = doc or near[:3]
    s = 'PX4 %s "%s"%s: PX4\'s description, the parameters%s and its source line in each release (%s to %s).' % (
        armcat.KIND_LABEL[r["kind"]], it["title"], " (event ID %s)" % r["event_id"] if r.get("event_id") else "",
        " (%s)" % ", ".join(ps) if ps else "", all_tags[0], all_tags[-1])
    return s if len(s) <= 300 else s[:297] + "..."


def _source_excerpt(src):
    lines = (src or "").split("\n")
    if len(lines) <= SOURCE_MAX_LINES:
        return "\n".join(lines), 0
    return "\n".join(lines[:SOURCE_MAX_LINES]), len(lines) - SOURCE_MAX_LINES


def render_page(it, items, all_tags, shas, base_url=BASE_URL):
    e = html.escape
    r = it["rec"]
    kind = armcat.KIND_LABEL[r["kind"]]
    head_id = r.get("event_id") or it["check"]
    parts = ["<!doctype html>", '<html lang="en"><head><meta charset="utf-8">',
             '<meta name="viewport" content="width=device-width, initial-scale=1">',
             "<title>%s - PX4 %s (%s)</title>" % (e(it["title"]), e(kind), e(head_id)),
             '<meta name="description" content="%s">' % e(_meta_description(it, all_tags)),
             '<link rel="canonical" href="%s">' % e("%sm/%s.html" % (base_url, it["slug"])),
             STYLE, "</head><body>",
             '<p><a href="../index.html">PX4 health and arming check messages</a> &rsaquo; '
             '<a href="../messages.html#%s">%s</a></p>' % (e(it["check"]), e(it["check"])),
             "<h1>%s</h1>" % e(it["title"])]
    intro = "PX4 %s" % e(kind)
    if r.get("event_id"):
        intro += ", event ID <code>%s</code>" % e(r["event_id"])
    intro += ", reported by <code>%s</code>" % e(it["check"])
    if r.get("function"):
        intro += " in <code>%s</code>" % e(r["function"])
    bits = _kind_bits(r)
    if bits:
        intro += "; " + "; ".join(e(b) for b in bits)
    parts.append("<p>%s.</p>" % intro)
    if RE_PLACEHOLDER.search(it["title"]):
        parts.append("<p>Parts in braces, such as <code>{1}</code>, are filled in by PX4 when the message is "
                     "sent.</p>")
    console = r.get("console") or []
    if console:
        parts.append("<h2>Console text</h2><p>Printed to the MAVLink console next to this report:</p><ul>")
        for c in console:
            txt = c.get("text") if c.get("text") is not None else (c.get("text_raw") or "")
            parts.append("<li><code>%s</code> (%s)</li>" % (e(txt), e(c.get("level") or "")))
        parts.append("</ul>")
    if r.get("summary") or r.get("description"):
        parts.append("<h2>What PX4 says</h2>")
        for para in [p for p in [r.get("summary") or ""] + (r.get("description") or "").split("\n\n") if p]:
            parts.append("<p>%s</p>" % e(para))
        parts.append("<p><small>From the EVENT comment above the check in PX4's source (%s).</small></p>"
                     % e(it["latest_tag"]))
    doc, near = _params(r)
    if doc or near:
        parts.append("<h2>Parameters</h2>")
        if doc:
            parts.append("<p>Named by PX4 in its description: %s</p>"
                         % ", ".join("<code>%s</code>" % e(p) for p in doc))
        if near:
            parts.append("<p>Used in the code just before this check (found by a simple scan; they may not "
                         "control this message): %s</p>" % ", ".join("<code>%s</code>" % e(p) for p in near))
    parts.append("<h2>Releases</h2><table><tr><th>Release</th><th>Message</th><th>Source</th></tr>")
    for tag in all_tags:
        pt = it["per_tag"].get(tag)
        if pt is None:
            parts.append("<tr><td>%s</td><td colspan=\"2\">not present</td></tr>" % e(tag))
            continue
        rt = pt["rec"]
        where = "%s line %d" % (rt["path"].rsplit("/", 1)[-1], rt["line"])
        if pt["calls"] > 1:
            where += " (%d calls)" % pt["calls"]
        parts.append('<tr><td>%s</td><td>%s</td><td><a href="%s">%s</a></td></tr>' % (
            e(tag), e(title_of(rt)), e(changes._url(rt, shas.get(tag, ""))), e(where)))
    parts.append("</table>")
    src, more = _source_excerpt(r.get("source"))
    if src.strip():
        parts.append("<h2>Source (%s)</h2>" % e(it["latest_tag"]))
        parts.append("<pre><code>%s</code></pre>" % e(src))
        if more:
            parts.append("<p>(%d more lines at the source link above.)</p>" % more)
    sib = [x for x in items if x["check"] == it["check"] and x["slug"] != it["slug"]]
    if sib:
        parts.append("<h2>Other messages from %s</h2><ul>" % e(it["check"]))
        for x in sib:
            parts.append('<li><a href="%s.html">%s</a></li>' % (e(x["slug"]), e(x["title"])))
        parts.append("</ul>")
    parts.append('<p>What changed between releases: <a href="../changes.html">changes</a>. To check a flight log '
                 '(vibration, GPS, battery, failsafes) in your browser without uploading it: '
                 '<a href="%s">PX4 log check</a>.</p>' % e(armcat.CHECKER_URL))
    parts.append("<hr><p><small>%s</small></p></body></html>" % e(FOOT % __version__))
    return "\n".join(parts) + "\n"


def render_index(items, all_tags):
    e = html.escape
    checks = []
    for it in items:
        if it["check"] not in checks:
            checks.append(it["check"])
    parts = ["<!doctype html>", '<html lang="en"><head><meta charset="utf-8">',
             '<meta name="viewport" content="width=device-width, initial-scale=1">',
             "<title>Every PX4 health and arming check message (%s to %s)</title>" % (e(all_tags[0]), e(all_tags[-1])),
             '<meta name="description" content="Every PX4 health and arming check message (Preflight Fail, arming '
             'denied) from %s to %s, each with its own page: parameters, PX4\'s description and source line.">'
             % (e(all_tags[0]), e(all_tags[-1])),
             STYLE, "</head><body>",
             "<h1>Every PX4 health and arming check message</h1>",
             "<p>%d messages from %d check files in PX4 %s, read from PX4's own source by armcat.py. Each links to a "
             "page with the console text, PX4's description, the parameters and the source line in every release. "
             'The full catalogue for one release is on <a href="index.html">this page</a>; what changed between '
             'releases is <a href="changes.html">here</a>.</p>'
             % (len(items), len(checks), e(", ".join(all_tags)))]
    for check in checks:
        parts.append('<h2 id="%s">%s</h2><ul>' % (e(check), e(check)))
        for it in items:
            if it["check"] != check:
                continue
            extra = armcat.KIND_LABEL[it["rec"]["kind"]]
            if it["tags"] != all_tags:
                extra += "; in %s" % ", ".join(it["tags"])
            eid = " <code>%s</code>" % e(it["rec"]["event_id"]) if it["rec"].get("event_id") else ""
            parts.append('<li><a href="m/%s.html">%s</a>%s (%s)</li>' % (e(it["slug"]), e(it["title"]), eid, e(extra)))
        parts.append("</ul>")
    parts.append("<hr><p><small>%s</small></p></body></html>" % e(FOOT % __version__))
    return "\n".join(parts) + "\n"


def render_sitemap(items, base_url=BASE_URL, lastmod=None):
    urls = [base_url, base_url + "changes.html", base_url + "messages.html"]
    urls += ["%sm/%s.html" % (base_url, it["slug"]) for it in items]
    lm = "<lastmod>%s</lastmod>" % html.escape(lastmod) if lastmod else ""
    body = "".join("<url><loc>%s</loc>%s</url>\n" % (html.escape(u), lm) for u in urls)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + body + "</urlset>\n")


def link_index(path):
    """Add one link to messages.html to armcat.py's index.html (before its first <h2>). True if changed."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if LINK_MARK in text:
        return False
    snippet = ('%s<p>Every message on its own page, with its parameters and source in each release: '
               '<a href="messages.html">all messages</a>.</p>\n' % LINK_MARK)
    i = text.find("<h2")
    if i < 0:
        i = text.find("</body>")
    text = text + snippet if i < 0 else text[:i] + snippet + text[i:]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True


def _write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def build_site(out_dir, dest, base_url=BASE_URL):
    tags, by_tag, shas = changes.load(out_dir)
    lastmod = None
    try:
        with open(os.path.join(out_dir, "summary.json"), encoding="utf-8") as f:
            lastmod = (json.load(f).get("finished") or "")[:10] or None
    except (OSError, ValueError):
        pass
    tags = [t for t in tags if t in by_tag]
    items = collect(tags, by_tag)
    if not items:
        return items, tags
    os.makedirs(os.path.join(dest, "m"), exist_ok=True)
    for it in items:
        _write(os.path.join(dest, "m", it["slug"] + ".html"), render_page(it, items, tags, shas, base_url))
    _write(os.path.join(dest, "messages.html"), render_index(items, tags))
    _write(os.path.join(dest, "sitemap.xml"), render_sitemap(items, base_url, lastmod))
    meta = [{"slug": it["slug"], "key": it["key"], "event_id": it["rec"].get("event_id"), "check": it["check"],
             "kind": it["rec"]["kind"], "title": it["title"], "tags": it["tags"]} for it in items]
    with open(os.path.join(dest, "pages.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({"tool": "pages.py", "version": __version__, "tags": tags, "pages": meta}, f, indent=1,
                  ensure_ascii=False)
        f.write("\n")
    idx = os.path.join(dest, "index.html")
    if os.path.isfile(idx):
        link_index(idx)
    return items, tags


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("out_dir")
    ap.add_argument("--dest")
    ap.add_argument("--base-url", default=BASE_URL)
    a = ap.parse_args(argv)
    base = a.base_url if a.base_url.endswith("/") else a.base_url + "/"
    items, tags = build_site(a.out_dir, a.dest or a.out_dir, base)
    by_kind = {}
    for it in items:
        by_kind[it["rec"]["kind"]] = by_kind.get(it["rec"]["kind"], 0) + 1
    print(json.dumps({"pages": len(items), "by_kind": by_kind,
                      "not_in_newest": sum(1 for it in items if tags and it["latest_tag"] != tags[-1]),
                      "checks": len({it["check"] for it in items})}, indent=1), flush=True)
    return 0 if items else 1


if __name__ == "__main__":
    sys.exit(main())
